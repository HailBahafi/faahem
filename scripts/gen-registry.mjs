// Regenerates src/content/lessons/index.ts and src/components/problems/index.ts from the files on disk.
// Lessons are ordered as in the roadmap; each lesson's `problem.demo` key is matched to
// src/components/problems/<Key>Problem.tsx (case-insensitive). Run: npm run registry
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const LESSONS = "src/content/lessons";
const PROBLEMS = "src/components/problems";

const order = [...readFileSync("src/content/roadmap.ts", "utf8").matchAll(/L\("([^"]+)"/g)].map((m) => m[1]);
const problemFiles = readdirSync(PROBLEMS).filter((f) => f.endsWith("Problem.tsx")).map((f) => f.replace(".tsx", ""));
const byKey = new Map(problemFiles.map((n) => [n.replace(/Problem$/, "").toLowerCase(), n]));

const lessons = [];
const missing = [];
for (const f of readdirSync(LESSONS).filter((f) => f.endsWith(".ts") && f !== "index.ts")) {
  const src = readFileSync(`${LESSONS}/${f}`, "utf8");
  const name = src.match(/export const (\w+)\s*:\s*Lesson/)?.[1];
  const slug = src.match(/slug:\s*"([^"]+)"/)?.[1];
  const demo = src.match(/demo:\s*"([^"]+)"/)?.[1];
  if (!name || !slug) { missing.push(`${f}: no exported Lesson`); continue; }
  const comp = demo && byKey.get(demo.toLowerCase());
  if (demo && !comp) missing.push(`${f}: no component for demo "${demo}"`);
  lessons.push({ file: f.replace(".ts", ""), name, slug, demo, comp });
}
const rank = (s) => (order.indexOf(s) < 0 ? 1e9 : order.indexOf(s));
lessons.sort((a, b) => rank(a.slug) - rank(b.slug));

const byFile = [...lessons].sort((a, b) => a.file.localeCompare(b.file));
writeFileSync(
  `${LESSONS}/index.ts`,
  `// Generated by scripts/gen-registry.mjs (npm run registry). Do not edit by hand.
import type { Lesson } from "@/lib/types";
${byFile.map((l) => `import { ${l.name} } from "./${l.file}";`).join("\n")}

/** Every published lesson, in roadmap order. */
export const lessons: Record<string, Lesson> = Object.fromEntries(
  [${lessons.map((l) => l.name).join(", ")}].map((l) => [l.slug, l]),
);
`,
);

const demos = new Map(lessons.filter((l) => l.comp).map((l) => [l.demo, l.comp]));
const comps = [...new Set(demos.values())].sort();
writeFileSync(
  `${PROBLEMS}/index.tsx`,
  `// Generated by scripts/gen-registry.mjs (npm run registry). Do not edit by hand.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

// Each demo loads only when its lesson opens, so a lesson page doesn't ship all ${comps.length} of them.
const load = (f: () => Promise<{ default: ComponentType }>) =>
  dynamic(f, { loading: () => <div className="h-64 animate-pulse rounded-2xl bg-surface-2" /> });

/** Interactive "why do we need this?" demos, keyed by \`lesson.problem.demo\`. */
export const PROBLEMS: Record<string, ComponentType> = {
${[...demos].map(([k, c]) => `  ${/^[a-zA-Z_]\w*$/.test(k) ? k : JSON.stringify(k)}: load(() => import("./${c}")),`).join("\n")}
};
`,
);

// Stage projects: every src/content/projects/*.ts exporting a Project.
const PROJECTS = "src/content/projects";
const projects = readdirSync(PROJECTS)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => ({ file: f.replace(".ts", ""), name: readFileSync(`${PROJECTS}/${f}`, "utf8").match(/export const (\w+)\s*:\s*Project/)?.[1] }))
  .filter((p) => p.name)
  .sort((a, b) => a.file.localeCompare(b.file));
writeFileSync(
  `${PROJECTS}/index.ts`,
  `// Generated by scripts/gen-registry.mjs (npm run registry). Do not edit by hand.
import type { Project } from "@/lib/types";
${projects.map((p) => `import { ${p.name} } from "./${p.file}";`).join("\n")}

export const projects: Record<string, Project> = Object.fromEntries(
  [${projects.map((p) => p.name).join(", ")}].map((p) => [p.slug, p]),
);

/** The project of each stage, by stage number. */
export const projectOfStage = (stage: number) => Object.values(projects).find((p) => p.stage === stage);
`,
);

// A tiny index for pages that only need to know what exists (the roadmap, lesson links,
// certificates), so they don't ship every lesson's content to the browser.
const stageProjects = {};
for (const p of projects) {
  const src = readFileSync(`${PROJECTS}/${p.file}.ts`, "utf8");
  const stage = Number(src.match(/stage:\s*(\d+)/)?.[1]);
  stageProjects[stage] = { slug: src.match(/slug:\s*"([^"]+)"/)?.[1], title: src.match(/title:\s*"([^"]+)"/)?.[1] };
}
writeFileSync(
  "src/content/published.ts",
  `// Generated by scripts/gen-registry.mjs (npm run registry). Do not edit by hand.
/** Slugs of every published lesson. */
export const PUBLISHED_LESSONS = new Set<string>(${JSON.stringify(lessons.map((l) => l.slug))});

/** Each stage's project, by stage number. */
export const STAGE_PROJECTS: Record<number, { slug: string; title: string }> = ${JSON.stringify(stageProjects, null, 2)};
`,
);

console.log(`${lessons.length} lessons, ${demos.size} demos, ${projects.length} projects registered`);
if (missing.length) {
  console.log(missing.map((m) => "  ! " + m).join("\n"));
  process.exitCode = 1;
}
